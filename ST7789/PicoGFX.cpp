void PicoGFX::fillScreen(uint16_t color) { fillRect(0, 0, _width, _height, color); }

void PicoGFX::drawLine(int16_t x0, int16_t y0, int16_t x1, int16_t y1, uint16_t color) {
  int16_t steep = abs(y1 - y0) > abs(x1 - x0);
  if (steep) { int16_t t=x0; x0=y0; y0=t; t=x1; x1=y1; y1=t; }
  if (x0 > x1) { int16_t t=x0; x0=x1; x1=t; t=y0; y0=y1; y1=t; }
  int16_t dx = x1 - x0, dy = abs(y1 - y0);
  int16_t err = dx / 2, ystep = (y0 < y1) ? 1 : -1;
  for (; x0 <= x1; x0++) {
    if (steep) drawPixel(y0, x0, color); else drawPixel(x0, y0, color);
    err -= dy; if (err < 0) { y0 += ystep; err += dx; }
  }
}

void PicoGFX::drawFastVLine(int16_t x, int16_t y, int16_t h, uint16_t color) { drawLine(x, y, x, y+h-1, color); }
void PicoGFX::drawRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
  drawLine(x, y, x+w-1, y, color); drawLine(x, y+h-1, x+w-1, y+h-1, color);
  drawLine(x, y, x, y+h-1, color); drawLine(x+w-1, y, x+w-1, y+h-1, color);
}

void PicoGFX::drawCircle(int16_t x0, int16_t y0, int16_t r, uint16_t color) {
  int16_t f = 1 - r, ddF_x = 1, ddF_y = -2 * r, x = 0, y = r;
  drawPixel(x0, y0+r, color); drawPixel(x0, y0-r, color); drawPixel(x0+r, y0, color); drawPixel(x0-r, y0, color);
  while (x < y) {
    if (f >= 0) { y--; ddF_y += 2; f += ddF_y; }
    x++; ddF_x += 2; f += ddF_x;
    drawPixel(x0+x, y0+y, color); drawPixel(x0-x, y0+y, color); drawPixel(x0+x, y0-y, color); drawPixel(x0-x, y0-y, color);
    drawPixel(x0+y, y0+x, color); drawPixel(x0-y, y0+x, color); drawPixel(x0+y, y0-x, color); drawPixel(x0-y, y0-x, color);
  }
}

void PicoGFX::fillCircle(int16_t x0, int16_t y0, int16_t r, uint16_t color) {
  drawLine(x0, y0-r, x0, y0+r, color);
  int16_t f = 1 - r, ddF_x = 1, ddF_y = -2 * r, x = 0, y = r;
  while (x < y) {
    if (f >= 0) { y--; ddF_y += 2; f += ddF_y; }
    x++; ddF_x += 2; f += ddF_x;
    drawLine(x0+x, y0-y, x0+x, y0+y, color); drawLine(x0-x, y0-y, x0-x, y0+y, color);
    drawLine(x0+y, y0-x, x0+y, y0+x, color); drawLine(x0-y, y0-x, x0-y, y0+x, color);
  }
}

size_t PicoGFX::write(uint8_t c) {
  if (!_gfxFont) {
    if (c == '\n') { cursor_x = 0; cursor_y += textsize_y * 8; }
    else if (c != '\r') {
      if (wrap && ((cursor_x + textsize_x * 6) > _width)) { cursor_x = 0; cursor_y += textsize_y * 8; }
      drawChar(cursor_x, cursor_y, c, textcolor, textbgcolor, textsize_x, textsize_y);
      cursor_x += textsize_x * 6;
    }
  } else {
    if (c == '\n') { cursor_x = 0; cursor_y += (int16_t)textsize_y * _gfxFont->yAdvance; }
    else if (c != '\r') {
      uint8_t first = _gfxFont->first;
      if ((c >= first) && (c <= (uint8_t)_gfxFont->last)) {
        GFXglyph *glyph = &_gfxFont->glyph[c - first];
        uint8_t w = glyph->width, h = glyph->height;
        if ((w > 0) && (h > 0)) {
          int16_t xo = (int8_t)glyph->xOffset;
          if (wrap && ((cursor_x + textsize_x * (xo + w)) > _width)) {
            cursor_x = 0; cursor_y += (int16_t)textsize_y * _gfxFont->yAdvance;
          }
          drawChar(cursor_x, cursor_y, c, textcolor, textbgcolor, textsize_x, textsize_y);
        }
        cursor_x += (uint8_t)glyph->xAdvance * (int16_t)textsize_x;
      }
    }
  }
  return 1;
}

size_t PicoGFX::print(const char* str) { size_t n=0; while(*str) n+=write(*str++); return n; }
size_t PicoGFX::println(const char* str) { size_t n=print(str); n+=write('\r'); n+=write('\n'); return n; }
size_t PicoGFX::print(int n, int base) { char buf[12]; itoa(n, buf, base); return print(buf); }
size_t PicoGFX::println(int n, int base) { size_t r=print(n, base); r+=write('\r'); r+=write('\n'); return r; }

void PicoGFX::drawChar(int16_t x, int16_t y, unsigned char c, uint16_t color, uint16_t bg, uint8_t size_x, uint8_t size_y) {
  if ((x >= _width) || (y >= _height) || ((x + 6 * size_x - 1) < 0) || ((y + 8 * size_y - 1) < 0)) return;
  if (!_gfxFont) {
    if (!_cp437 && (c >= 176)) c++;
    for (int8_t i = 0; i < 5; i++) {
      uint8_t line = font[c * 5 + i];
      for (int8_t j = 0; j < 8; j++, line >>= 1) {
        if (line & 1) {
          if (size_x == 1 && size_y == 1) drawPixel(x + i, y + j, color);
          else fillRect(x + i * size_x, y + j * size_y, size_x, size_y, color);
        } else if (bg != color) {
          if (size_x == 1 && size_y == 1) drawPixel(x + i, y + j, bg);
          else fillRect(x + i * size_x, y + j * size_y, size_x, size_y, bg);
        }
      }
    }
    if (bg != color) drawFastVLine(x + 5 * size_x, y, 8 * size_y, bg);
  } else {
    c -= (uint8_t)_gfxFont->first;
    GFXglyph *glyph = &_gfxFont->glyph[c];
    uint8_t *bitmap = _gfxFont->bitmap;
    uint16_t bo = glyph->bitmapOffset;
    uint8_t w = glyph->width, h = glyph->height;
    int8_t xo = glyph->xOffset, yo = glyph->yOffset;
    int16_t xo16 = xo, yo16 = yo;
    if (size_x > 1 || size_y > 1) { xo16 = xo; yo16 = yo; }

    uint8_t xx, yy, bits = 0, bit = 0;
    for (yy = 0; yy < h; yy++) {
      for (xx = 0; xx < w; xx++) {
        if (!(bit++ & 7)) bits = bitmap[bo++];
        if (bits & 0x80) {
          if (size_x == 1 && size_y == 1) drawPixel(x + xo + xx, y + yo + yy, color);
          else drawRect(x + (xo16 + xx) * size_x, y + (yo16 + yy) * size_y, size_x, size_y, color);
        }
        bits <<= 1;
      }
    }
  }
}

